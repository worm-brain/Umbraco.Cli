def history_section(runs, scenario_key):
    """The page's History section: every run, the machines, and one table per scenario across CLI builds.

    :param runs: every `(stem, doc)`, oldest first.
    :param scenario_key: sort key for scenario names (bench.py's order first).
    :returns: the markdown.
    """
    run_rows, machines = [], {}
    for stem, doc in runs:
        rows, h = doc["results"], doc["hyperfine"]
        builds = sorted({r["cli"]["version"]: r["cli"] for r in rows}.values(), key=build_key)
        run_rows.append([run_link(stem, doc), doc["machine"]["label"], ", ".join(dict.fromkeys(r["umbraco"] for r in rows)),
                         ", ".join(build_name(c) for c in builds),
                         f"{h['version']}: {h['warmup']} warm-up + {h['runs']} timed runs; {doc['httpRuns']} HTTP runs",
                         doc.get("note") or ""])
        machines[doc["machine"]["label"]] = doc["machine"]  # the newest file's details win

    parts = [
        "## History across CLI versions",
        para("Every committed run, oldest first. The times are UTC, and each run links to its results file."),
        table(["Run", "Machine", "Umbraco", "CLI builds", "hyperfine", "Note"], "llllll", run_rows),
        para("The machines:"),
        table(["Machine", "CPU", "Logical cores", "RAM GiB", "OS", "Arch"], "llrrll",
              [[label, m["cpu"], str(m["logicalCores"]), "n/a" if m.get("memoryGiB") is None else str(m["memoryGiB"]),
                m["os"], m["arch"]] for label, m in sorted(machines.items())]),
        para("Each scenario below has one row per CLI build and run, published builds in version order and then "
             "local builds. End-to-end times include Umbraco's server time; CLI overhead is end-to-end minus HTTP "
             "time. Compare rows from the same machine only."),
    ]
    results = [(stem, doc, r) for stem, doc in runs for r in doc["results"]]
    for name in sorted({r["scenario"] for _, _, r in results}, key=scenario_key):
        mine = sorted((x for x in results if x[2]["scenario"] == name),
                      key=lambda x: (build_key(x[2]["cli"]), x[1]["date"], x[0], harness.version_key(x[2]["umbraco"])))
        commands = dict.fromkeys(f"`{display_command(r['command'])}`" for _, _, r in mine)
        parts += [f"### `{name}`", para(f"Command: {'; '.join(commands)}"),
                  table(["CLI", "Umbraco", "Run", "Machine", *RESULT_HEADERS], "llllrrrr",
                        [[build_name(r["cli"]), r["umbraco"], run_link(stem, doc), doc["machine"]["label"], *timing(r)]
                         for stem, doc, r in mine])]
    return "\n\n".join(parts)


def umbraco_section(runs, scenario_key):
    """The page's Umbraco comparison: the same build and scenario on more than one Umbraco major, on one machine.

    Takes the newest result for each machine, scenario, CLI build and exact Umbraco version, and shows the groups
    (machine, scenario, build) that cover more than one major. When there are none, it says "Not yet measured".

    :param runs: every `(stem, doc)`, oldest first.
    :param scenario_key: sort key for scenario names.
    :returns: the markdown.
    """
    newest = {}
    for stem, doc in runs:  # oldest first, so a newer run replaces an older one
        for r in doc["results"]:
            newest[(doc["machine"]["label"], r["scenario"], r["cli"]["version"], r["umbraco"])] = (stem, doc, r)
    groups = {}
    for (machine, scenario, version, _), found in newest.items():
        groups.setdefault((machine, scenario, version), []).append(found)
    compared = [found for group in groups.values() if len({major(r["umbraco"]) for _, _, r in group}) > 1
                for found in group]
    measured = sorted({r["umbraco"] for _, doc in runs for r in doc["results"]}, key=harness.version_key)
    majors = sorted({major(v) for v in measured}, key=harness.version_key)
    # With one major so far, suggest it and the next one; otherwise every major there are results for.
    wanted = majors if len(majors) > 1 else majors + [str(int(majors[0]) + 1)]
    how = code(f"{BENCH} --cli local --umbraco {','.join(wanted)}")

    parts = ["## Umbraco versions"]
    if not compared:
        if len(majors) > 1:
            said = (f"Results exist for Umbraco {', '.join(majors)}, but no machine has run the same CLI build on "
                    "more than one of them, so they can't be compared yet.")
        else:
            said = (f"Every result so far is on Umbraco {majors[0]} ({', '.join(measured)}). Once a run covers "
                    "another major, this section compares them.")
        return "\n\n".join(parts + [para(f"Not yet measured. {said} To measure it, run each version in one run on "
                                         "one machine:"), how])
    compared.sort(key=lambda x: (x[1]["machine"]["label"], scenario_key(x[2]["scenario"]), build_key(x[2]["cli"]),
                                 harness.version_key(x[2]["umbraco"])))
    return "\n\n".join(parts + [
        para("The same CLI build and scenario on more than one Umbraco major, on the same machine, from the newest "
             "run of each. HTTP time is where a change in Umbraco shows; the CLI overhead of one build should barely "
             "move between Umbraco versions. When the versions come from different runs, anything else that "
             "changed between those runs (load on the machine, an update) is in the difference too."),
        table(["Scenario", "CLI", "Umbraco", "Run", "Machine", *RESULT_HEADERS], "lllllrrrr",
              [[f"`{r['scenario']}`", build_name(r["cli"]), r["umbraco"], run_link(stem, doc), doc["machine"]["label"],
                *timing(r)] for stem, doc, r in compared]),
    ])


def rerun_command(doc, scenario_names):
    """The bench.py command that repeats a run: its builds, Umbraco versions, scenarios and hyperfine settings.

    :param doc: the run's results document.
    :param scenario_names: bench.py's scenario names; `--scenario` is added only when the run timed a subset.
    :returns: the command line.
    """
    rows, h = doc["results"], doc["hyperfine"]
    clis = dict.fromkeys("local" if is_local(r["cli"]) else r["cli"]["version"] for r in rows)
    cmd = [BENCH, "--cli", ",".join(clis), "--umbraco", ",".join(dict.fromkeys(r["umbraco"] for r in rows))]
    timed = list(dict.fromkeys(r["scenario"] for r in rows))
    if set(timed) != set(scenario_names):
        cmd += ["--scenario", ",".join(timed)]
    return " ".join(cmd + ["--warmup", str(h["warmup"]), "--runs", str(h["runs"]), "--http-runs", str(doc["httpRuns"])])


def reproduce_section(runs, scenario_names):
    """The page's Reproduce section: exact commands for each layer, each committed run, and this page.

    :param runs: every `(stem, doc)`, oldest first.
    :param scenario_names: bench.py's scenario names.
    :returns: the markdown.
    """
