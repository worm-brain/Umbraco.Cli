"""perf_report.py - render the README's Performance section and docs/performance.md from bench.py's results.

Run it through bench.py, from anywhere:

  python3 tests/hands-on/bench.py report

It reads every docs/performance/results/*.json that bench.py wrote (tests/hands-on/README.md, "Benchmarks",
documents the schema), then:

- rewrites only the lines between `<!-- perf:start -->` and `<!-- perf:end -->` in the repository's README.md:
  a headline table (startup, one `get`, one large export, each with its request count) for the newest published
  CLI build on the newest Umbraco version in the newest results file, stamped with the machine, versions and
  date. A `local` build is quoted only when that file has no published one, because readers install published
  builds;
- writes docs/performance.md whole: the method, every run, history per scenario across CLI builds, the Umbraco
  version comparison, how to reproduce every number, and the caveats.

All the prose on both pages lives in this file, and every number comes from a results file: to change the text,
edit it here and regenerate; to change a number, record a new run. The output depends only on the results files
and bench.py's scenario table, so running it again changes nothing, and it is ASCII only. It stops before
writing anything when there are no results files, a file can't be read or has another schemaVersion, or
README.md doesn't hold exactly one pair of markers.
"""
import argparse
import json
import re
import textwrap
import unicodedata

import harness
from harness import ROOT, die, say

REPO = ROOT.parent.parent
RESULTS = REPO / "docs" / "performance" / "results"
README = REPO / "README.md"
PAGE = REPO / "docs" / "performance.md"
START, END = "<!-- perf:start -->", "<!-- perf:end -->"
SCHEMA_VERSION = 1  # the results schema this report reads: bench.py's SCHEMA_VERSION
GITHUB = "https://github.com/worm-brain/Umbraco.Cli"
BENCH = "python3 tests/hands-on/bench.py"
WIDTH = 110  # prose line length in the generated markdown

# What the README quotes, in order: (scenario, what it shows). Startup, one item, and one large export.
HEADLINE = [("version", "Startup"), ("get", "Read one item"), ("content-export", "Export the content tree")]

# Punctuation the results could carry (in a CPU or OS name, or a CLI error), and its ASCII spelling.
ASCII = {"–": "-", "—": "-", "‘": "'", "’": "'", "“": '"', "”": '"', "…": "...",
         "×": "x", " ": " ", "®": "(R)", "™": "(TM)"}

# A line that markdown would read as the start of a list, quote, table, heading or setext underline.
BLOCK_START = re.compile(r"([-+*>|#]|\d+[.)])(\s|$)|(-+|=+)$")

GENERATED = ("<!-- Generated by `python3 tests/hands-on/bench.py report` from docs/performance/results/. Don't edit "
             "{what}: record a new run with bench.py, or change the text in tests/hands-on/tools/perf_report.py, "
             "then regenerate. -->")


# ---------------------------------------------------------------- input ------
def rel(path):
    """A path as messages show it: relative to the repository when it is inside it.

    :param path: an absolute path.
    :returns: the path, with forward slashes.
    """
    return path.relative_to(REPO).as_posix() if path.is_relative_to(REPO) else path.as_posix()


def load_results(folder):
    """Read every results file in a folder, oldest run first.

    :param folder: the results folder (docs/performance/results).
    :returns: a list of `(stem, doc)` pairs, ordered by each run's start and then its file name.
    :raises SystemExit: when there are no results files, or one can't be read or has another schemaVersion.
    """
    files = sorted(folder.glob("*.json")) if folder.is_dir() else []
    if not files:
        die(f"No results files in {rel(folder)}/, so there is nothing to report. Record a run first, for example:\n"
            f"  {BENCH} --cli local --umbraco 17\nNothing was written.")
    runs = []
    for path in files:
        try:
            doc = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:
            die(f"Can't read {rel(path)}: {e}. Nothing was written.")
        if not isinstance(doc, dict) or doc.get("schemaVersion") != SCHEMA_VERSION:
            found = doc.get("schemaVersion") if isinstance(doc, dict) else None
            die(f"{rel(path)} has schemaVersion {found!r}, and this report reads {SCHEMA_VERSION} only. Update "
                "tests/hands-on/tools/perf_report.py for the new schema. Nothing was written.")
        runs.append((path.stem, doc))
    return sorted(runs, key=lambda run: (run[1]["date"], run[0]))


# ---------------------------------------------------------------- builds -----
def is_local(cli):
    """Whether a result's CLI build was packed from a checkout (`--cli local`) rather than published.

    :param cli: a results row's `cli`.
    :returns: True for a local build.
    """
    return cli["label"] == "local"


def build_key(cli):
    """Sort key for CLI builds: published builds in version order, then local builds by the pack time in their version.

    :param cli: a results row's `cli`.
    :returns: a tuple that orders builds.
    """
    return is_local(cli), harness.version_key(cli["version"])


def build_name(cli):
    """A CLI build as the tables name it: its version, or `local <commit>` for a build of a checkout.

    :param cli: a results row's `cli`.
    :returns: the name.
    """
    return f"local {cli.get('commit') or ''}".rstrip() if is_local(cli) else cli["version"]


def major(version):
    """The major of an Umbraco version.

    :param version: an exact version such as "17.7.0".
    :returns: the major, e.g. "17".
    """
    return version.split(".")[0]


def headline(doc):
    """Choose what the README quotes from one results document.

    That is the document's newest Umbraco version with a successful result and, on that version, its newest
    published CLI build; a local build only when no published build succeeded on it.

    :param doc: the results document.
    :returns: `(Umbraco version, the build's cli, {scenario: row})`, the rows including failed ones.
    :raises SystemExit: when the document has no successful result at all.
    """
    ok = [r for r in doc["results"] if r["status"] == "ok"]
    if not ok:
        die(f"The newest results file ({doc['date']}) has no successful result, so the README has nothing to "
            "quote. Nothing was written.")
    umbraco = max((r["umbraco"] for r in ok), key=harness.version_key)
    on_it = [r["cli"] for r in ok if r["umbraco"] == umbraco]
    cli = max([c for c in on_it if not is_local(c)] or on_it, key=build_key)
    rows = {r["scenario"]: r for r in doc["results"] if r["umbraco"] == umbraco and r["cli"]["version"] == cli["version"]}
    return umbraco, cli, rows


# ---------------------------------------------------------------- text -------
def ms(value):
    """A millisecond value for a table.

    :param value: milliseconds, or None.
    :returns: one decimal, or "n/a".
    """
    return "n/a" if value is None else f"{value:.1f}"


def timing(row):
    """A result's four numeric cells.

    :param row: a results row.
    :returns: end-to-end mean +/- sd, HTTP ms, CLI overhead ms and requests; for a failed row, why and three blanks.
    """
    if row["status"] != "ok":
        error = " ".join((row.get("error") or "no error recorded").split())
        return [f"failed: {error if len(error) <= 80 else error[:77] + '...'}", "", "", ""]
    e2e = row["endToEndMs"]
    return [f"{ms(e2e['mean'])} +/- {ms(e2e['stddev'])}", ms(row["httpMs"]), ms(row["cliOverheadMs"]),
            str(row["requests"])]


def display_command(command):
    """A command as the docs show it, for reading rather than pasting.

    Drops the options every API scenario passes for isolation (`--output json --config {config}`), shows the
    scratch output file as `<file>` and the fixtures folder as its repository path, and any other placeholder
    (a fixture id such as `{home}`) as `<home>`.

    :param command: a results row's `command`, or a scenario's argv joined after `umbraco`.
    :returns: the command.
    """
    text = re.sub(r"\s--output\s+json\b|\s--config\s+\{config\}", "", command)
    text = re.sub(r"\{work\}/\S+", "<file>", text).replace("{fixtures}", "tests/hands-on/fixtures")
    return re.sub(r"\{(\w+)\}", r"<\1>", text)


def run_link(stem, doc):
    """A run as docs/performance.md links it.

    :param stem: the results file name without its extension.
    :param doc: its results document.
    :returns: the run's start (UTC, to the minute, with no space so it never wraps) linking to its results file.
    """
    return f"[{doc['date'][:16]}Z](performance/results/{stem}.json)"


def link(number, kind="issues"):
    """A link to a GitHub issue or pull request (a repository file doesn't autolink `#123`).

    :param number: the issue or PR number.
    :param kind: "issues" or "pull".
    :returns: the markdown link.
    """
    return f"[#{number}]({GITHUB}/{kind}/{number})"


# ---------------------------------------------------------------- markdown ---
def para(text, indent=""):
    """One paragraph of prose, wrapped at WIDTH.

    A wrapped line never starts with something markdown would read as a list item, quote, table or heading:
    such a line is joined to the one before it instead.

    :param text: the paragraph, with any spacing.
    :param indent: the first line's prefix (a list marker such as "- "); later lines get as many spaces.
    :returns: the wrapped paragraph.
    """
    lines = textwrap.wrap(" ".join(text.split()), WIDTH, initial_indent=indent, subsequent_indent=" " * len(indent),
                          break_long_words=False, break_on_hyphens=False)
    out = lines[:1]
    for line in lines[1:]:
        if BLOCK_START.match(line.strip()):
            out[-1] += " " + line.strip()
        else:
            out.append(line)
    return "\n".join(out)


def bullets(*items):
    """A bulleted list of prose items (each wrapped as `para` wraps).

    :param items: the items' text.
    :returns: the list.
    """
    return "\n".join(para(item, "- ") for item in items)


def table(headers, align, rows):
    """A markdown table.

    :param headers: the column headings.
    :param align: "l" or "r" per column.
    :param rows: lists of cell text. A `|` or line break in a cell is replaced, so the cell stays one cell.
    :returns: the table.
    """
    def cell(text):
        return " ".join(str(text).split()).replace("|", "/")
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" if a == "l" else "--:" for a in align) + "|"]
    return "\n".join(lines + ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows])


def code(text):
    """A fenced bash block.

    :param text: the commands.
    :returns: the block.
    """
    return f"```bash\n{text}\n```"


def ascii_only(text):
    """Text with only ASCII characters: known punctuation spelled out, accents dropped, anything else as "?".

    :param text: the generated markdown.
    :returns: the same text in ASCII.
    """
    text = unicodedata.normalize("NFKD", "".join(ASCII.get(c, c) for c in text))
    return "".join(c for c in text if not unicodedata.combining(c)).encode("ascii", "replace").decode("ascii")


RESULT_HEADERS = ["End-to-end ms (mean +/- sd)", "HTTP ms", "CLI overhead ms", "Requests"]


# ---------------------------------------------------------------- README -----
def readme_block(doc):
    """The README's Performance section: the headline table from one results document, and its stamp.

    :param doc: the newest results document.
    :returns: the markdown that goes between the markers.
    """
    umbraco, cli, rows = headline(doc)
    body = []
    for scenario, what in HEADLINE:
        row = rows.get(scenario)
        if row is None:
            body.append([what, "not measured in this run", "", ""])
        elif row["status"] != "ok":
            body.append([f"{what}: `{display_command(row['command'])}`", "failed (see docs/performance.md)", "", ""])
        else:
            e2e, _, overhead, requests = timing(row)
            body.append([f"{what}: `{display_command(row['command'])}`", e2e, overhead, requests])

    m, h = doc["machine"], doc["hyperfine"]
    build = cli["version"] + (f", commit {cli['commit']}" if cli.get("commit") else "")
    note = f" Note on this run: {doc['note']}" if doc.get("note") else ""
    return "\n\n".join([
        GENERATED.format(what="between the perf markers"),
        "## Performance",
        para("The CLI wraps Umbraco's Management API, so most of a command's time is Umbraco's; the CLI's own "
             "share is shown separately. CI gates request counts and allocations, never timings."),
        table(["Command", "End-to-end ms, including Umbraco server time", "CLI overhead ms", "HTTP requests"],
              "lrrr", body),
        para(f"Measured {doc['date'][:10]} on {m['cpu']}, {m['logicalCores']} logical cores, {m['os']}: CLI {build} "
             f"(.NET {cli.get('dotnet') or 'unknown'}) against Umbraco {umbraco} on the same machine (the test "
             f"harness's dev site). Mean +/- standard deviation of {h['runs']} hyperfine runs. CLI overhead is "
             "end-to-end minus the time in HTTP requests: startup, auth, parsing, the CLI's own work and output."
             f"{note}"),
        para("Method, history across CLI versions, caveats and how to reproduce every number: "
             "[docs/performance.md](docs/performance.md)."),
    ])


