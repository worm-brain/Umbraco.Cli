def read_raw(path):
    """A file's text exactly as it is on disk, line endings included.

    :param path: the file.
    :returns: the text, or None when there is no file.
    """
    if not path.is_file():
        return None
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def replace_block(text, block):
    """README.md's text with the block between the markers replaced, and nothing else changed.

    Works on the text as it is on disk, so every byte outside the block, line endings included, stays as it was;
    the block takes the file's line endings.

    :param text: README.md as `read_raw` returns it.
    :param block: the new block, with "\\n" line endings.
    :returns: the new text.
    :raises SystemExit: when there is no README.md, or it doesn't hold exactly one start marker followed by one
        end marker.
    """
    if text is None:
        die(f"{rel(README)} is missing. Nothing was written.")
    starts, ends = text.count(START), text.count(END)
    if starts != 1 or ends != 1 or text.index(START) > text.index(END):
        found = "the end marker comes first" if starts == ends == 1 else f"found {starts} start and {ends} end markers"
        die(f"{rel(README)} must hold one {START} line and, after it, one {END} line, around the Performance "
            f"section ({found}). Put the two lines where the section goes, then run this again. Nothing was written.")
    newline = "\r\n" if "\r\n" in text else "\n"
    head, rest = text.split(START, 1)
    return head + START + newline + block.replace("\n", newline) + newline + END + rest.split(END, 1)[1]


def write(path, old, new):
    """Write a file only when its text changes.

    :param path: the file.
    :param old: its current text (None when it doesn't exist).
    :param new: the text it should have.
    :returns: whether the file was written.
    """
    if old == new:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(new)
    return True


def main(argv, scenarios):
    """Regenerate the README's Performance block and docs/performance.md (`bench.py report`).

    :param argv: the arguments after `report`.
    :param scenarios: bench.py's SCENARIOS: the scenario order, and the table of what each one runs.
    :raises SystemExit: as the module docstring says, before anything is written.
    """
    argparse.ArgumentParser(prog="bench.py report", description=__doc__,
                            formatter_class=argparse.RawDescriptionHelpFormatter).parse_args(argv)
    runs = load_results(RESULTS)
    stem, doc = runs[-1]

    # ---- render both, and check the README's markers, before writing either --------
    old_readme = read_raw(README)
    new_readme = replace_block(old_readme, ascii_only(readme_block(doc)))
    old_page = read_raw(PAGE)
    newline = "\r\n" if old_page and "\r\n" in old_page else "\n"  # keep the checkout's line endings
    new_page = ascii_only(render_page(runs, scenarios)).replace("\n", newline)

    for path, old, new in ((README, old_readme, new_readme), (PAGE, old_page, new_page)):
        say(f"{rel(path)}: {'updated' if write(path, old, new) else 'unchanged'}")
    umbraco, cli, _ = headline(doc)
    print(f"    from {len(runs)} results file(s); the README quotes CLI {build_name(cli)} on Umbraco {umbraco} "
          f"from {stem}")
