def caveats_section(runs):
    """The page's Caveats section: noise (with each run's note), and what the HTTP and overhead split can't see.

    :param runs: every `(stem, doc)`, oldest first.
    :returns: the markdown.
    """
    noted = [f"{run_link(stem, doc)}: {doc['note']}" for stem, doc in runs if doc.get("note")]
    noise = ("**Noise.** Each number comes from one run on one machine. hyperfine's standard deviation is the "
             "spread to compare against: a difference smaller than the two results' spreads added together is "
             "noise. Other load on the machine (builds, test runs, other benchmarks) widens the spread and moves "
             "the means, so a run meant for committing should be on a quiet machine, and a run that wasn't says so "
             "in its note." + (" Runs with a note:" if noted else " No run has a note so far."))
    others = bullets(
        "**End-to-end includes Umbraco.** It is what a user waits for: the CLI plus Umbraco's server time, here on "
        "a local site with the harness's small fixture content. A real site, a remote host or another Umbraco "
        "version moves it. Compare CLI overhead across CLI builds, and HTTP time across Umbraco versions.",
        "**HTTP time is more than server time.** It is everything inside the HTTP stack. In particular, the first "
        "request of each process opens the connection (TCP and the TLS handshake) and pays for the first use of "
        ".NET's HTTP stack, so a command that makes any request has some HTTP time even when Umbraco answers "
        "at once.",
        "**CLI overhead includes reading response bodies.** The CLI's clock for a request stops at the response "
        "headers, so reading the body counts as CLI overhead. On localhost that part is small.",
        "**Only requests a build logs are counted.** Builds before 0.1.0-alpha.15 don't log the OAuth token "
        "exchange under `--verbose`, and builds before 0.1.0-alpha.14 have no token cache, so they exchange a token "
        "on every run. For those builds (such as 0.1.0-alpha.6) the token round trip is in CLI overhead, and it is "
        "missing from their request counts.",
        "**Logged durations are whole milliseconds,** truncated, so bench.py adds half a millisecond to each.",
        "**Builds do different work.** A later build's command can make more requests than an earlier one's (more "
        "follow-up reads, for a fuller result), so compare the request counts before the times. A failed row is a "
        "build without that command or snapshot format, not a slow one.",
        "**Machines differ.** Numbers from different machines aren't comparable. Compare rows from the same "
        "machine.",
    )
    # One list, so it renders tight: the noise item, the runs' notes nested under it, then the other items.
    return "\n\n".join(["## Caveats", "\n".join([bullets(noise), *(para(n, "  - ") for n in noted), others])])


def render_page(runs, scenarios):
    """docs/performance.md, whole.

    :param runs: every `(stem, doc)`, oldest first.
    :param scenarios: bench.py's SCENARIOS.
    :returns: the markdown.
    """
    order = {s.name: i for i, s in enumerate(scenarios)}

    def scenario_key(name):
        return order.get(name, len(order)), name
    stem, doc = runs[-1]
    umbraco, cli, _ = headline(doc)
    return "\n\n".join([
        "# Performance",
        GENERATED.format(what="this file"),
        para("How fast the `umbraco` CLI is, how that is measured, and how to reproduce every number here. The CLI "
             "wraps Umbraco's Management API, so most of a command's wall time is spent in Umbraco. The parts the "
             "CLI owns are process startup, config and authentication, how many requests a command makes, and its "
             "own CPU: parsing, writing output, and the export, diff and apply engines."),
        para(f"The [README](../README.md#performance) quotes CLI {build_name(cli)} on Umbraco {umbraco} from the run "
             f"of {run_link(stem, doc)}. Every run is under "
             "[History across CLI versions](#history-across-cli-versions)."),
        method_section(scenarios),
        history_section(runs, scenario_key),
        umbraco_section(runs, scenario_key),
        reproduce_section(runs, [s.name for s in scenarios]),
        caveats_section(runs),
    ]) + "\n"


